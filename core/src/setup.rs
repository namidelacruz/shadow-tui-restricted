//! `shadow setup` — per-user first run (and `--remove`).
//! Creates ~/.config/shadow-state/config.toml with every default written out (commented), and
//! migrates from Shadow Network / NETDIVE: keeps term/AI settings, retires the configs the old
//! engine generated for niri, waybar, mako, swaylock, foot, yazi and fuzzel, and turns off the old
//! per-user units. Nothing is deleted: everything moved aside lands in a dated folder.
use crate::{st, sys};
use std::path::{Path, PathBuf};

const OLD_USER_UNITS: [&str; 6] = ["shadownet-update.path", "shadow-layout.service", "shadow-opt-agent.service", "shadownet-wifi-guard.service", "shadow-backup.timer", "netdive-update.path"];
const RETIRED: [&str; 9] = ["waybar/config", "waybar/config.jsonc", "waybar/style.css", "mako/config", "swaylock/config", "foot/foot.ini", "yazi/theme.toml", "fuzzel/fuzzel.ini", "shadow-network/compositor.kdl"];
const SHELL_TAG: &str = "# shadow-network shell integration";

