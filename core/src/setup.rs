fn say(m: &str) { println!("\x1b[38;2;255;176;0m▌\x1b[0m {m}"); }
fn info(m: &str) { println!("\x1b[38;2;0;229;255m  ·\x1b[0m {m}"); }

fn user_units(args: &[&str]) -> bool {
    if sys::which("systemctl").is_none() {
        return false;
    }
    let mut v = vec!["systemctl", "--user"];
    v.extend_from_slice(args);
    sys::run(&v).0 == 0
}

fn xdg_config() -> PathBuf {
    std::env::var_os("XDG_CONFIG_HOME").filter(|v| !v.is_empty()).map(PathBuf::from).unwrap_or_else(|| st::home().join(".config"))
}

fn generated(p: &Path) -> bool {
    std::fs::read_to_string(p).map(|t| t.contains("GENERATED BY SHADOW NETWORK") || t.contains("GENERATED BY NETDIVE")).unwrap_or(false)
        || std::fs::read_link(p).map(|l| l.to_string_lossy().contains("shadow-network")).unwrap_or(false)
}

/// Shadow Network / NETDIVE leftovers → moved aside (returns how many)
pub fn retire(aside: &Path) -> usize {
    let xc = xdg_config();
    let mut n = 0;
    for rel in RETIRED {
        let f = xc.join(rel);
        if (f.is_file() || f.is_symlink()) && generated(&f) {
            let d = aside.join(rel);
            let _ = std::fs::create_dir_all(d.parent().unwrap());
            if std::fs::rename(&f, &d).is_ok() {
                n += 1;
                info(&format!("retired ~/.config/{rel}"));
            }
        }
    }
    // an older Shadow Network niri config, generated into ~/.config/niri: moved aside so a plain
    // niri session is clean (Shadow's own niri config now lives in ~/.config/shadow-state)
    let niri = xc.join("niri/config.kdl");
    if niri.is_file() && generated(&niri) {
        let d = aside.join("niri/config.kdl");
        let _ = std::fs::create_dir_all(d.parent().unwrap());
        if std::fs::rename(&niri, &d).is_ok() {
            n += 1;
            info("retired the old generated ~/.config/niri/config.kdl");
            let pre = xc.join("niri/config.kdl.pre-shadow-network");
            if pre.exists() && std::fs::rename(&pre, &niri).is_ok() {
                info("restored your pre-Shadow niri config");
            }
        }
    }
    n
}

fn migrate(state: &Path) {
    let old = xdg_config().join("shadow-network");
    for (from, to) in [("term.user.conf", "term.conf"), ("ai.conf", "ai.conf")] {
        if old.join(from).exists() && !state.join(to).exists() && std::fs::copy(old.join(from), state.join(to)).is_ok() {
            info(&format!("kept your {from} as {to}"));
        }
    }
    // a few settings carry over by meaning
    if let Ok(t) = std::fs::read_to_string(old.join("settings.json")) {
        if let Ok(v) = crate::json::parse(&t) {
            if let Some(repo) = v.path_str(&["updates", "repo"]).filter(|r| !r.is_empty()) {
                let _ = st::set("updates", "repo", &st::q(&repo));
                info("kept your update source");
            }
            if let Some(b) = v.path_bool(&["wifi", "self_correct"]) {
                let _ = st::set("wifi", "self_correct", &b.to_string());
            }
        }
    }
}

fn shell_integration(remove: bool) {
    let script = st::share().join("shell");
    for (rc, file) in [(st::home().join(".bashrc"), "shadow-term.bash"), (st::home().join(".zshrc"), "shadow-term.zsh")] {
        let text = std::fs::read_to_string(&rc).unwrap_or_default();
        if remove {
            let mut out = vec![];
            let mut skip = false;
            for l in text.split_inclusive('\n') {
                if l.trim() == SHELL_TAG { skip = true; continue; }
                if skip { skip = false; if l.contains("SHADOW_TERM") { continue; } }
                out.push(l);
            }
            if text.contains(SHELL_TAG) {
                let _ = std::fs::write(&rc, out.concat());
            }
        } else if (rc.exists() || rc.ends_with(".bashrc")) && !text.contains(SHELL_TAG) {
            use std::io::Write;
            if let Ok(mut f) = std::fs::OpenOptions::new().create(true).append(true).open(&rc) {
                let s = script.join(file);
                let _ = write!(f, "\n{SHELL_TAG}\nif [ -n \"$SHADOW_TERM\" ] && [ -r {s} ]; then . {s}; fi\n", s = s.display());
            }
        }
    }
}

pub fn install(yes: bool) -> i32 {
    let _ = yes;
    if sys::is_root() {
        eprintln!("shadow setup: run as your normal user, not root");
        return 1;
    }
    say("Shadow TUI Restricted user setup");
    let state = st::state_dir();
    let _ = std::fs::create_dir_all(&state);
    let cfg = state.join("config.toml");
    let fresh = !cfg.exists();
    if fresh {
        let _ = std::fs::write(&cfg, DEFAULT_CONFIG);
        info(&format!("created {}", cfg.display()));
    }
    migrate(&state);
    for u in OLD_USER_UNITS {
        if user_units(&["disable", "--now", u]) {
            info(&format!("turned off old unit {u}"));
        }
    }
    let aside = st::local_state().join(format!("retired-{}", sys::run(&["date", "+%Y%m%d-%H%M%S"]).1));
    let n = retire(&aside);
    if n > 0 {
        info(&format!("{n} file(s) from older versions kept in {}", aside.display()));
    }
    shell_integration(false);
    niri_config(false);
    // the folder default is Shadow's file manager unless one was chosen in Preferences
    if sys::which("xdg-mime").is_some() && st::get_in(&std::fs::read_to_string(st::state_dir().join("config.toml")).unwrap_or_default(), "defaults", "files").is_none() {
        sys::run(&["xdg-mime", "default", "shadow-files.desktop", "inode/directory"]);
    }
    user_units(&["daemon-reload"]);
    if dmi_is_dell_14_plus() && fresh {
        info("Dell 14 Plus: 1.5× scale (automatic), 120 Hz on AC / 60 Hz on battery");
    }
    say("Done. Pick “Shadow TUI Restricted” at the login screen (or run shadow-session on a TTY).");
    println!("   Keep your setup on GitHub: shadow-sync init --github shadow-state && shadow-sync push");
    0
}

fn dmi_is_dell_14_plus() -> bool {
    let p = sys::read("sys/class/dmi/id/product_name").unwrap_or_default();
    p.contains("14 Plus") || p.contains("DB14250")
}

pub fn remove(purge: bool) -> i32 {
    say("Removing Shadow TUI Restricted from this account");
    user_units(&["disable", "--now", "shadow-sync.timer"]);
    shell_integration(true);
    if purge {
        let _ = std::fs::remove_dir_all(st::local_state());
        info("removed ~/.local/state/shadow-tui (your ~/.config/shadow-state is kept: it is your synced state)");
    }
    say(&format!("Done. To remove the programs: {}", if crate::distro::family() == crate::distro::Family::Rpm { "sudo dnf remove shadow-tui-restricted shadow-tui-sec" } else { "sudo pacman -R shadow-tui-restricted shadow-tui-sec" }));
    0
}

/// `shadow setup compositor` (also `shadow setup niri`, its old name): a running shadow-compositor
/// re-reads config.toml now. 0 = reloaded or nothing to reload, 1 = the compositor refused it.
pub fn niri_config(verbose: bool) -> i32 {
    if shadow_niri::shadow_compositor().is_none() {
        if verbose {
            println!("shadow-compositor is not running: it reads config.toml when it starts");
        }
        return 0;
    }
    match shadow_niri::compositor_command("config-reload") {
        Ok(_) => {
            if verbose {
                println!("shadow-compositor reloaded config.toml");
            }
            0
        }
        Err(e) => {
            eprintln!("shadow setup compositor: {e}");
            1
        }
    }
}

pub fn main(args: &[&str]) -> i32 {
    if matches!(args.first(), Some(&"niri") | Some(&"compositor")) {
        return niri_config(true);
    }
    if args.contains(&"--remove") {
        return remove(args.contains(&"--purge"));
    }
    install(args.contains(&"--yes") || args.contains(&"-y"))
}

